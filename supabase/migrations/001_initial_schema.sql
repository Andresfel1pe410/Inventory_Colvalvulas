-- Política: Solo admin puede insertar/eliminar (asumiendo rol 'admin' tiene id=1)
-- Usamos una función para verificar si el usuario es admin
CREATE OR REPLACE FUNCTION es_admin(auth_uid UUID)
RETURNS BOOLEAN AS $$
BEGIN
    RETURN EXISTS (
        SELECT 1 FROM usuario u
        JOIN usuario_rol ur ON u.id = ur.usuario_id
        JOIN rol r ON ur.rol_id = r.id
        WHERE u.auth_user_id = auth_uid AND r.nombre = 'admin'
    );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

